from google import genai

from backend.config import settings


class GeminiGenerationError(Exception):
    """Raised when AI document generation fails."""


class GeminiGenerator:
    """Small service layer responsible for calling Gemini."""

    def __init__(self) -> None:
        if not settings.gemini_api_key:
            raise GeminiGenerationError(
                "GEMINI_API_KEY is not configured. Add it to the local .env file."
            )
        self.client = genai.Client(api_key=settings.gemini_api_key)
        self.model = settings.gemini_model

    def generate_legal_document(
        self,
        document_type: str,
        parties: str,
        purpose: str,
        terms: str,
        effective_date: str,
        jurisdiction: str,
    ) -> str:
        prompt = f"""
You are LegalEase, an AI-assisted legal drafting tool.

Create a professional FIRST DRAFT from the supplied information.
Never invent facts, names, dates, amounts, laws, addresses, clauses,
or jurisdiction-specific requirements that the user did not provide.
Use [MISSING INFORMATION] for important missing details.

DOCUMENT TYPE: {document_type}
JURISDICTION: {jurisdiction}
PARTIES: {parties}
PURPOSE: {purpose}
EFFECTIVE DATE: {effective_date}
TERMS / REQUIREMENTS: {terms}

Writing requirements:
- Use a clear legal-document structure.
- Keep terminology consistent throughout the document.
- Include only sections relevant to the supplied information.
- Include a signature section with placeholders.
- Do not provide legal advice or claim that the draft guarantees a legal result.
- Return only the draft document, without markdown fences or reasoning.

Suggested structure where applicable:
1. Title
2. Purpose and background
3. Parties
4. Definitions
5. Scope and obligations
6. Payment / consideration
7. Confidentiality
8. Intellectual property
9. Term and termination
10. Representations and responsibilities
11. Dispute resolution
12. Governing law (only when supplied)
13. Miscellaneous
14. Signatures

Finish with this notice:
AI DRAFT NOTICE: This document was generated by LegalEase using generative AI.
It should be reviewed by a qualified legal professional before being signed or relied upon.
"""
        try:
            interaction = self.client.interactions.create(
                model=self.model,
                input=prompt,
                store=False,
            )
            generated_text = getattr(interaction, "output_text", None)
            if not generated_text or not generated_text.strip():
                raise GeminiGenerationError("Gemini returned an empty response.")
            return generated_text.strip()
        except GeminiGenerationError:
            raise
        except Exception as exc:
            raise GeminiGenerationError(f"Gemini generation failed: {exc}") from exc


def generate_legal_document(**kwargs) -> str:
    return GeminiGenerator().generate_legal_document(**kwargs)
